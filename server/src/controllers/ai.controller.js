import { aiEngine } from '../services/ai-engine.service.js';
import WaitingPrediction from '../models/WaitingPrediction.js';
import AIRecommendation from '../models/AIRecommendation.js';
import { success } from '../utils/response.js';
import { asyncHandler } from '../utils/async.js';

/** Trigger a full AI engine cycle manually (admin). */
export const triggerCycle = asyncHandler(async (req, res) => {
  const results = await aiEngine.runCycle();
  return success(res, results, 'AI engine cycle complete');
});

/** Current live waiting predictions. */
export const currentPredictions = asyncHandler(async (req, res) => {
  const predictions = await aiEngine.broadcastWaitingPredictions();
  return success(res, predictions, 'Waiting predictions');
});

/** Recent waiting prediction history. */
export const predictionHistory = asyncHandler(async (req, res) => {
  const history = await WaitingPrediction.find({}).sort({ createdAt: -1 }).limit(50).populate('doctor', 'name staffId').exec();
  return success(res, history, 'Prediction history');
});

/** Recent AI recommendations generated by the engine. */
export const recentRecommendations = asyncHandler(async (req, res) => {
  const recs = await AIRecommendation.find({}).sort({ createdAt: -1 }).limit(50).populate('patient', 'name').exec();
  return success(res, recs, 'AI recommendations');
});

export const aiController = {
  triggerCycle,
  currentPredictions,
  predictionHistory,
  recentRecommendations,
};
